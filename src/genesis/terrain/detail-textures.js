/* detail-textures.js — the layer stack, uploaded.
 *
 * All the material authoring moved to terrain/detail-layers.js, which is pure
 * and testable. What is left here is the part that genuinely needs three.js:
 * two DataArrayTextures and their lifetime.
 *
 * ── WHY AN ARRAY TEXTURE RATHER THAN MORE SAMPLERS ──
 * The old set was three albedo+normal pairs bound as six independent
 * sampler2Ds. That is not a stack, it is a hard-coded list: a fourth material
 * cost two more uniforms, two more fetches and another arm in the blend, so
 * the ground was turf-rock-sand on every world forever. Ten layers the same
 * way would be twenty samplers, which is most of the guaranteed minimum
 * (WebGL2 promises 16 per stage) spent on ground.
 *
 * WebGL2 has TEXTURE_2D_ARRAY for exactly this. Ten layers of albedo are ONE
 * sampler2DArray and one fetch; ten normals are a second. Two samplers total,
 * down from six, while the number of materials went from three to ten — which
 * is the whole point of B1 and the reason sampler pressure went DOWN rather
 * than up.
 *
 * ── THE UPLOAD PATH, VERIFIED RATHER THAN ASSUMED ──
 * three's WebGLTextures uploads a DataArrayTexture with texStorage3D followed
 * by texSubImage3D, allocating `levels` mip levels up front, and sets
 * TEXTURE_WRAP_R alongside S and T. It also honours `generateMipmaps` for the
 * TEXTURE_2D_ARRAY target. All four of those were read out of
 * vendor/three/three.module.min.js before this file was written, because a
 * DataArrayTexture that silently fails to mip is a ground that aliases into
 * static at fifty metres and looks like a shader bug.
 *
 * Mips are not optional here. The fine tap repeats every ~2 m of world, so by
 * mid-distance one screen pixel covers many texels; without a mip chain that
 * is aliasing, and with anisotropy it is the difference between ground and
 * glitter.
 *
 * ── AND THE SHADER SAMPLES IT WITH texture2D() ──
 * which looks wrong and is not. three compiles every non-raw material as
 * `#version 300 es` and prepends `#define texture2D texture`, so the call
 * becomes GLSL3's overloaded `texture(sampler2DArray, vec3)`. Writing
 * `texture()` directly would work too and would break the day anything on
 * this material is compiled as GLSL1. Staying on the macro is the
 * conservative choice and it keeps this shader's fetches all spelled alike.
 */

import * as THREE from "three";
import { makeLayerStack, LAYER_NAMES, LAYER_INDEX, LAYER_PARAMS, LAYER_RES } from "./detail-layers.js";

export { LAYER_NAMES, LAYER_INDEX, LAYER_PARAMS, LAYER_RES };

function arrayTexture(data, res, count, { srgb = false, anisotropy = 4 }) {
  const tex = new THREE.DataArrayTexture(data, res, res, count);
  tex.format = THREE.RGBAFormat;
  tex.type = THREE.UnsignedByteType;
  // RepeatWrapping on S and T because these tile in world space. R is the
  // LAYER axis — clamped, because layer 10.5 is not a material.
  tex.wrapS = tex.wrapT = THREE.RepeatWrapping;
  tex.wrapR = THREE.ClampToEdgeWrapping;
  tex.magFilter = THREE.LinearFilter;
  tex.minFilter = THREE.LinearMipmapLinearFilter;
  tex.generateMipmaps = true;
  tex.anisotropy = anisotropy;
  // Albedo is colour and must be gamma-decoded; a normal map is a direction
  // and decoding it would bend every light in the world by a wrong amount.
  if (srgb) tex.colorSpace = THREE.SRGBColorSpace;
  else tex.colorSpace = THREE.NoColorSpace;
  tex.needsUpdate = true;
  return tex;
}

/* Wrap generated bytes as the pair of array textures the shader binds. */
function setFromBuffers(albedoBytes, normalBytes, norm, res, count, aniso) {
  const albedo = arrayTexture(albedoBytes, res, count, { srgb: true, anisotropy: aniso });
  const normal = arrayTexture(normalBytes, res, count, { anisotropy: aniso });
  return {
    albedo, normal, count,
    // Per-layer neutral-multiplier reciprocals, measured off the generated
    // pixels — see detail-layers.js on why this cannot be a constant.
    norm,
    names: LAYER_NAMES.slice(),
    params: LAYER_NAMES.map((n) => LAYER_PARAMS[n]),
    dispose() { albedo.dispose(); normal.dispose(); },
  };
}

/* → { albedo, normal, count, params, dispose() }. Deterministic per seed: the
   same world always grows the same ground. Synchronous, which costs about
   420 ms of main thread for the full stack — prefer makeDetailSetAsync.

   The WHOLE stack is generated, not just the layers the current palette
   selects. The set is keyed by SEED and the palette can change under it at
   any time (a style swap is five uniform writes, not a rebuild) — generating
   on demand would turn a free palette change into half a second of noise, in
   the one place a person would certainly notice it. */
export function makeDetailSet(seed, quality) {
  const stack = makeLayerStack(seed);
  return setFromBuffers(stack.albedo, stack.normal, stack.norm, stack.res, stack.count, quality?.anisotropy ?? 4);
}

/* The same set, generated in a worker. Resolves to null if the worker cannot
   be started or fails — the caller falls back, and a world with no detail set
   renders exactly as the low tier does rather than not at all.

   `makeWorker` is injected rather than imported so this module does not have
   to know about the engine's trusted-types gate (engine/trusted.js), which is
   what every `new Worker` on this origin has to pass through. */
export function makeDetailSetAsync(seed, quality, makeWorker) {
  return new Promise((resolve) => {
    let worker;
    try { worker = makeWorker(); } catch { resolve(null); return; }
    let settled = false;
    const done = (v) => { if (settled) return; settled = true; worker.terminate(); resolve(v); };
    worker.onmessage = (ev) => {
      const { albedo, normal, norm, res, count } = ev.data;
      done(setFromBuffers(new Uint8Array(albedo), new Uint8Array(normal),
        new Float32Array(norm), res, count, quality?.anisotropy ?? 4));
    };
    worker.onerror = (err) => {
      console.warn("[engine] detail-stack bake failed:", err.message);
      done(null);
    };
    worker.postMessage({ seed });
  });
}
