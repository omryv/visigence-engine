import assert from 'node:assert/strict';
import { makeGame, flatLevel } from './runtime-fixture.mjs';
import { OBJECTIVE, FIXED_STEP } from '../../src/config/gameplay.js';
import { State } from '../../src/sim/GameState.js';

const level = flatLevel(8);
level.placements = [0, 1].map(i => ({ id: 'terminal', role: 'objective', objectiveIndex: i,
  x: i * 10, y: 8, z: -8, height: 2, radius: 0.5, collision: 'circle' }));
const g = makeGame({ level });
assert.equal(g.objectives.hudState.total, 2);
g.player.position.set(0, 8, -6);
g.player.prevPosition.copy(g.player.position);
g.step({ interact: true });
assert.equal(g.interactions.target.id, 'objective:0', 'own prop must not occlude interaction');
for (let i = 0; i < 30; i++) g.step({ interact: true });
const progress = g.objectives.stations[0].progress;
assert(progress > 0 && progress < 1);
g.pause(); g.advance(5, { interact: true });
assert.equal(g.objectives.stations[0].progress, progress, 'pause freezes activation');
g.resume(); g.step();
assert(g.objectives.stations[0].progress < progress, 'release decays activation');
for (let i = 0; i < Math.ceil(OBJECTIVE.activationTime / FIXED_STEP) + 1; i++) g.step({ interact: true });
assert.equal(g.objectives.hudState.completed, 1);
assert.equal(g.objectives.phase, 'ACTIVATE');
g.player.position.set(10, 8, -6);
for (let i = 0; i < Math.ceil(OBJECTIVE.activationTime / FIXED_STEP) + 1; i++) g.step({ interact: true });
assert.equal(g.objectives.hudState.completed, 2);
assert.equal(g.objectives.phase, 'UNLOCKING');
assert.equal(g.state.current, State.PLAYING);
for (let i = 0; i < Math.ceil(OBJECTIVE.extractionDelay / FIXED_STEP) + 1; i++) g.step();
assert.equal(g.objectives.phase, 'EXTRACT');
assert.equal(g.state.current, State.PLAYING, 'stations alone do not win');
g.player.reset(level.spawn); g.step();
assert.equal(g.state.current, State.VICTORY);
g.restart();
assert.equal(g.objectives.hudState.completed, 0);
assert.equal(g.objectives.phase, 'ACTIVATE');
assert.equal(g.interactions.items.size, 2);
g.player.damage(10000); g.step();
assert.equal(g.state.current, State.PLAYER_DEAD);
g.dispose();
assert.equal(g.interactions.items.size, 0);
const sandbox = makeGame();
for (let i = 0; i < 120; i++) sandbox.step();
assert.equal(sandbox.state.current, State.PLAYING, 'empty levels cannot auto-win');
sandbox.dispose();
console.log('Placed objectives, elevated hold interactions, pause/restart, extraction, victory and death passed');
